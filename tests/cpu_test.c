static void t_modes(void) {
  PROG(NATIVE, STP);
  CHECK(!cpu.e && flag(CPU_C) && flag(CPU_M) && flag(CPU_X));
  PROG(REP(0x30), STP);
  CHECK(cpu.e && (cpu.p & 0x30) == 0x30);
  PROG(NATIVE, REP(0x30), 0xa2, 0x34, 0x12, 0xa0, 0x78, 0x56, STP);
  CHECK(cpu.x == 0x1234 && cpu.y == 0x5678 && !flag(CPU_M) && !flag(CPU_X));
  PROG(NATIVE, REP(0x30), 0xa2, 0x34, 0x12, 0xa0, 0x78, 0x56, SEP(0x10), STP);
  CHECK(cpu.x == 0x34 && cpu.y == 0x78);
  PROG(NATIVE, REP(0x30), 0xa9, 0x00, 0x1f, 0x1b, 0xa2, 0x34, 0x12, 0x38, 0xfb, STP);
  CHECK(cpu.e && !flag(CPU_C) && cpu.s == 0x0100 && cpu.x == 0x34 && (cpu.p & 0x30) == 0x30);
  PROG(NATIVE, 0x18, 0xfb, STP);
  CHECK(!cpu.e && !flag(CPU_C));
}

static void t_stack(void) {
  PROG(NATIVE, REP(0x30), 0xa9, 0x34, 0x12, 0x48, 0xa9, 0, 0, 0x68, STP);
  CHECK(cpu.a == 0x1234 && cpu.s == 0x1ff && mem[0x1fe] == 0x34 && mem[0x1ff] == 0x12);
  PROG(0xa9, 0x42, 0x48, 0xa9, 0x00, 0x68, STP);
  CHECK((cpu.a & 0xff) == 0x42 && !flag(CPU_Z) && cpu.s == 0x1ff);
  PROG(NATIVE, SEP(0xcb), 0x08, REP(0xcb), 0x28, STP);
  CHECK((cpu.p & 0xcb) == 0xcb && mem[0x1ff] == 0xff);
  PROG(NATIVE, REP(0x10), 0xa2, 0x34, 0x12, SEP(0x10), 0x08, REP(0x10), 0xa2, 0x34, 0x12,
       0x28, STP);
  CHECK(flag(CPU_X) && cpu.x == 0x34);
  PROG(NATIVE, 0xf4, 0xcd, 0xab, STP);
  CHECK(cpu.s == 0x1fd && mem[0x1fe] == 0xcd && mem[0x1ff] == 0xab);
  setup();
  LOAD(0x8000, NATIVE, 0xd4, 0x10, STP);
  mem[0x10] = 0x78; mem[0x11] = 0x56;
  run();
  CHECK(cpu.s == 0x1fd && mem[0x1fe] == 0x78 && mem[0x1ff] == 0x56);
  PROG(NATIVE, 0x62, 0x10, 0x00, STP);
  CHECK(mem[0x1fe] == 0x15 && mem[0x1ff] == 0x80);
  PROG(NATIVE, 0xa9, 0x7e, 0x48, 0xab, 0x8b, 0x4b, STP);
  CHECK(cpu.db == 0x7e && mem[0x1ff] == 0x7e && mem[0x1fe] == 0x00 && cpu.s == 0x1fd);
  PROG(NATIVE, REP(0x20), 0xa9, 0x00, 0x03, 0x5b, 0x0b, 0xa9, 0, 0, 0x5b, 0x2b, STP);
  CHECK(cpu.d == 0x0300 && mem[0x1ff] == 0x03 && mem[0x1fe] == 0x00 && cpu.s == 0x1ff);
  PROG(NATIVE, REP(0x10), 0xa2, 0x22, 0x11, 0xa0, 0x44, 0x33, 0xda, 0x5a, 0xfa, 0x7a, STP);
  CHECK(cpu.x == 0x3344 && cpu.y == 0x1122);
  //Emulation-mode push wraps within page 1.
  PROG(0xa2, 0x00, 0x9a, 0xa9, 0x55, 0x48, STP);
  CHECK(cpu.s == 0x1ff && mem[0x100] == 0x55);
  //PEA in emulation writes below page 1, S.h then forced to 1.
  PROG(0xa2, 0x00, 0x9a, 0xf4, 0xcd, 0xab, STP);
  CHECK(mem[0x100] == 0xab && mem[0x0ff] == 0xcd && cpu.s == 0x1fe);
}

static void t_calls(void) {
  setup();
  LOAD(0x8000, 0x20, 0x00, 0x90, STP);
  LOAD(0x9000, 0xa9, 0x42, 0x60);
  run();
  CHECK((cpu.a & 0xff) == 0x42 && cpu.s == 0x1ff && cpu.pc == 0x8004 && mem[0x1ff] == 0x80
        && mem[0x1fe] == 0x02);
  setup();
  LOAD(0x8000, NATIVE, 0x22, 0x00, 0x80, 0x01, STP);
  LOAD(0x018000, 0xa9, 0x99, 0x4b, 0xab, 0x6b);
  run();
  CHECK((cpu.a & 0xff) == 0x99 && cpu.db == 0x01 && cpu.pb == 0 && cpu.s == 0x1ff
        && mem[0x1ff] == 0x00 && mem[0x1fe] == 0x80 && mem[0x1fd] == 0x05);
  setup();
  LOAD(0x8000, NATIVE, REP(0x10), 0xa2, 0x02, 0x00, 0xfc, 0x00, 0x90, STP);
  LOAD(0x9002, 0x00, 0xa0);
  LOAD(0xa000, 0xa9, 0x11, 0x60);
  run();
  CHECK((cpu.a & 0xff) == 0x11 && cpu.s == 0x1ff && cpu.pc == 0x800b);
  setup();
  LOAD(0x8000, 0x6c, 0x00, 0x30, 0xea);
  LOAD(0x3000, 0x00, 0x90);
  LOAD(0x9000, 0xa9, 0x01, STP);
  run();
  CHECK((cpu.a & 0xff) == 0x01);
  setup();
  LOAD(0x8000, NATIVE, 0x5c, 0x00, 0x80, 0x02);
  LOAD(0x028000, 0xa2, 0x04, 0x7c, 0x00, 0x90);
  LOAD(0x029004, 0x00, 0xa0);
  LOAD(0x009004, 0x00, 0xb0);
  LOAD(0x02a000, 0xa9, 0x22, STP);
  run();
  CHECK((cpu.a & 0xff) == 0x22 && cpu.pb == 2);
  setup();
  LOAD(0x8000, NATIVE, 0xdc, 0x00, 0x30);
  LOAD(0x3000, 0x00, 0x80, 0x05);
  LOAD(0x058000, 0xa9, 0x33, STP);
  run();
  CHECK((cpu.a & 0xff) == 0x33 && cpu.pb == 5);
}

