static void t_transfers(void) {
  PROG(NATIVE, REP(0x20), 0xa9, 0x34, 0x12, 0xeb, STP);
  CHECK(cpu.a == 0x3412 && !flag(CPU_Z) && !flag(CPU_N));
  PROG(NATIVE, REP(0x20), 0xa9, 0xff, 0x00, 0xeb, STP);
  CHECK(cpu.a == 0xff00 && flag(CPU_Z) && !flag(CPU_N));
  PROG(NATIVE, REP(0x30), 0xa9, 0x00, 0x1f, 0x1b, 0xa9, 0, 0, 0x3b, STP);
  CHECK(cpu.s == 0x1f00 && cpu.a == 0x1f00);
  PROG(NATIVE, REP(0x20), 0xa9, 0x00, 0x21, 0x5b, 0xa9, 0, 0, 0x7b, STP);
  CHECK(cpu.d == 0x2100 && cpu.a == 0x2100);
  PROG(0xa2, 0x80, 0x9a, STP);
  CHECK(cpu.s == 0x180);
  PROG(NATIVE, REP(0x10), 0xa2, 0x80, 0x12, 0x9a, 0xba, STP);
  CHECK(cpu.s == 0x1280 && cpu.x == 0x1280);
  //TCS in emulation keeps S.h = 1; TSC transfers full S.
  PROG(0xa9, 0x40, 0x1b, 0x3b, STP);
  CHECK(cpu.s == 0x140 && cpu.a == 0x140);
  //TAX: 16-bit the hero takes B even with 8-bit A.
  PROG(NATIVE, REP(0x30), 0xa9, 0x34, 0x12, SEP(0x20), 0xaa, STP);
  CHECK(cpu.x == 0x1234);
  //TXA with 8-bit A preserves B.
  PROG(NATIVE, REP(0x30), 0xa9, 0x34, 0x12, 0xa2, 0x80, 0x00, SEP(0x20), 0x8a, STP);
  CHECK(cpu.a == 0x1280 && flag(CPU_N));
  PROG(NATIVE, REP(0x30), 0xa9, 0x34, 0x12, SEP(0x10), 0xa8, 0xbb, 0x9b, STP);
  CHECK(cpu.y == 0x34 && cpu.x == 0x34);
}

static void t_indirect(void) {
  //(dp),Y crosses into next bank.
  setup();
  LOAD(0x8000, NATIVE, REP(0x10), 0xa9, 0x01, 0x48, 0xab, 0xa0, 0x02, 0x00, 0xb1, 0x10, STP);
  mem[0x10] = 0xff; mem[0x11] = 0xff; mem[0x020001] = 0x5a;
  run();
  CHECK((cpu.a & 0xff) == 0x5a);
  setup();
  LOAD(0x8000, NATIVE, 0xa7, 0x10, 0xa0, 0x01, 0xb7, 0x10, 0x85, 0x20, STP);
  mem[0x10] = 0x00; mem[0x11] = 0x40; mem[0x12] = 0x7e;
  mem[0x7e4000] = 0x11; mem[0x7e4001] = 0x22;
  run();
  CHECK((cpu.a & 0xff) == 0x22 && mem[0x20] == 0x22);
  setup();
  LOAD(0x8000, 0xa2, 0x04, 0xa1, 0x10, 0x72, 0x20, STP);
  mem[0x14] = 0x00; mem[0x15] = 0x30; mem[0x3000] = 0x10;
  mem[0x20] = 0x01; mem[0x21] = 0x30; mem[0x3001] = 0x05;
  run();
  CHECK((cpu.a & 0xff) == 0x15);
  //(sr,S),Y
  setup();
  LOAD(0x8000, NATIVE, 0xf4, 0x00, 0x30, 0xa0, 0x02, 0xb3, 0x01, STP);
  mem[0x3002] = 0x77;
  run();
  CHECK((cpu.a & 0xff) == 0x77);
  //sr,S store
  setup();
  LOAD(0x8000, NATIVE, 0xf4, 0x00, 0x00, 0xa9, 0x66, 0x83, 0x02, STP);
  run();
  CHECK(mem[0x1ff] == 0x66);
  //long,X
  setup();
  LOAD(0x8000, NATIVE, 0xa2, 0x03, 0xbf, 0xfe, 0xff, 0x12, STP);
  mem[0x130001] = 0x44;
  run();
  CHECK((cpu.a & 0xff) == 0x44);
  //abs,X crosses bank with DB=1.
  setup();
  LOAD(0x8000, NATIVE, 0xa9, 0x01, 0x48, 0xab, 0xa2, 0x02, 0xbd, 0xff, 0xff, STP);
  mem[0x020001] = 0x99;
  run();
  CHECK((cpu.a & 0xff) == 0x99);
  //16-bit abs read at $FFFF takes high byte from next bank.
  setup();
  LOAD(0x8000, NATIVE, REP(0x20), 0xad, 0xff, 0xff, STP);
  mem[0x00ffff] = 0x34; mem[0x010000] = 0x12;
  run();
  CHECK(cpu.a == 0x1234);
  //16-bit dp read at D+$FF..: wraps within bank 0.
  setup();
  LOAD(0x8000, NATIVE, REP(0x20), 0xa9, 0x00, 0xff, 0x5b, 0xa5, 0xff, STP);
  mem[0xffff] = 0x78; mem[0x0000] = 0x56;
  run();
  CHECK(cpu.a == 0x5678);
  //Emulation, DL=0: dp,X wraps within page.
  setup();
  LOAD(0x8000, NATIVE, REP(0x20), 0xa9, 0x00, 0x01, 0x5b, 0x38, 0xfb, 0xa2, 0x02,
       0xb5, 0xff, STP);
  mem[0x0101] = 0xaa; mem[0x0201] = 0xbb;
  run();
  CHECK(cpu.e && (cpu.a & 0xff) == 0xaa);
  //Native: same crosses page.
  setup();
  LOAD(0x8000, NATIVE, REP(0x20), 0xa9, 0x00, 0x01, 0x5b, SEP(0x20), 0xa2, 0x02,
       0xb5, 0xff, STP);
  mem[0x0101] = 0xaa; mem[0x0201] = 0xbb;
  run();
  CHECK((cpu.a & 0xff) == 0xbb);
  //Emulation, DL!=0: no page wrap.
  setup();
  LOAD(0x8000, NATIVE, REP(0x20), 0xa9, 0x01, 0x01, 0x5b, 0x38, 0xfb, 0xa2, 0x02,
       0xb5, 0xff, STP);
  mem[0x0102] = 0xaa; mem[0x0202] = 0xcc;
  run();
  CHECK((cpu.a & 0xff) == 0xcc);
  //Emulation (dp),Y pointer high byte wraps within page.
  setup();
  LOAD(0x8000, 0xa0, 0x00, 0xb1, 0xff, STP);
  mem[0xff] = 0x00; mem[0x00] = 0x40; mem[0x100] = 0x50; mem[0x4000] = 0x12;
  run();
  CHECK((cpu.a & 0xff) == 0x12);
}

static void t_interrupts(void) {
  //Native NMI.
  setup();
  LOAD(0x8000, NATIVE, 0xf8, 0x5c, 0x00, 0x80, 0x03);
  LOAD(0x038000, 0xea, 0xea, 0xea);
  mem[0xffea] = 0x00; mem[0xffeb] = 0x90;
  LOAD(0x9000, STP);
  for (int i = 0; i < 4; i++) cpu_step(&cpu);
  uint8_t p0 = cpu.p;
  cpu.nmi_pending = true;
  cpu_step(&cpu);
  CHECK(!cpu.nmi_pending && cpu.pc == 0x9000 && cpu.pb == 0 && cpu.s == 0x1fb);
  CHECK(mem[0x1ff] == 0x03 && mem[0x1fe] == 0x80 && mem[0x1fd] == 0x00 && mem[0x1fc] == p0);
  CHECK(flag(CPU_I) && !flag(CPU_D));
  //RTI native restores PB.
  LOAD(0x9000, 0x40);
  cpu_step(&cpu);
  CHECK(cpu.pb == 3 && cpu.pc == 0x8000 && cpu.p == p0 && cpu.s == 0x1ff);
  //Emulation NMI.
  setup();
  LOAD(0x8000, 0xf8, 0xea);
  mem[0xfffa] = 0x00; mem[0xfffb] = 0x90;
  cpu_step(&cpu);
  cpu.nmi_pending = true;
  cpu_step(&cpu);
  CHECK(cpu.pc == 0x9000 && cpu.s == 0x1fc && mem[0x1ff] == 0x80 && mem[0x1fe] == 0x01);
  CHECK(mem[0x1fd] == ((0x34 | CPU_D) & ~0x10) && flag(CPU_I) && !flag(CPU_D));
  //IRQ masked by I, then taken after CLI.
  setup();
  LOAD(0x8000, NATIVE, 0xea, 0x58, 0xea);
  mem[0xffee] = 0x00; mem[0xffef] = 0xa0;
  cpu.irq_line = true;
  cpu_step(&cpu); cpu_step(&cpu); cpu_step(&cpu);
  CHECK(cpu.pc == 0x8003);
  cpu_step(&cpu);
  CHECK(cpu.pc == 0x8004 && !flag(CPU_I));
  cpu_step(&cpu);
  CHECK(cpu.pc == 0xa000 && flag(CPU_I) && cpu.s == 0x1fb);
  //Emulation IRQ vector.
  setup();
  LOAD(0x8000, 0x58, 0xea);
  mem[0xfffe] = 0x00; mem[0xffff] = 0xb0;
  cpu_step(&cpu);
  cpu.irq_line = true;
  cpu_step(&cpu);
  CHECK(cpu.pc == 0xb000 && cpu.s == 0x1fc);
  //BRK native: pushes PC+2, vector $FFE6.
  setup();
  LOAD(0x8000, NATIVE, 0x00, 0x55);
  mem[0xffe6] = 0x00; mem[0xffe7] = 0xc0;
  cpu_step(&cpu); cpu_step(&cpu); cpu_step(&cpu);
  CHECK(cpu.pc == 0xc000 && mem[0x1fe] == 0x80 && mem[0x1fd] == 0x04 && cpu.s == 0x1fb);
  //BRK emulation: B set in pushed P.
  setup();
  LOAD(0x8000, 0x00, 0x55);
  mem[0xfffe] = 0x00; mem[0xffff] = 0xc0;
  cpu_step(&cpu);
  CHECK(cpu.pc == 0xc000 && (mem[0x1fd] & 0x10) && mem[0x1fe] == 0x02 && cpu.s == 0x1fc);
  //COP native and emulation.
  setup();
  LOAD(0x8000, NATIVE, 0x02, 0x00);
  mem[0xffe4] = 0x00; mem[0xffe5] = 0xd0;
  cpu_step(&cpu); cpu_step(&cpu); cpu_step(&cpu);
  CHECK(cpu.pc == 0xd000);
  setup();
  LOAD(0x8000, 0x02, 0x00);
  mem[0xfff4] = 0x00; mem[0xfff5] = 0xd0;
  cpu_step(&cpu);
  CHECK(cpu.pc == 0xd000 && cpu.s == 0x1fc);
  //WAI: idles until IRQ; with I set resumes without vectoring.
  setup();
  LOAD(0x8000, 0xcb, 0xe8, STP);
  cpu_step(&cpu);
  CHECK(cpu.waiting);
  unsigned long c0 = cycles;
  cpu_step(&cpu);
  CHECK(cpu.waiting && cpu.pc == 0x8001 && cycles == c0 + 1);
  cpu.irq_line = true;
  cpu_step(&cpu);
  CHECK(!cpu.waiting && cpu.x == 1 && cpu.pc == 0x8002);
  //WAI woken by NMI vectors.
  setup();
  LOAD(0x8000, 0xcb, STP);
  mem[0xfffa] = 0x00; mem[0xfffb] = 0x90;
  cpu_step(&cpu);
  cpu.nmi_pending = true;
  cpu_step(&cpu);
  CHECK(!cpu.waiting && cpu.pc == 0x9000 && mem[0x1fe] == 0x01);
  //STP idles forever.
  PROG(STP);
  c0 = cycles;
  cpu.nmi_pending = true;
  cpu_step(&cpu);
  CHECK(cpu.stopped && cycles == c0 + 1 && cpu.pc == 0x8001);
}

static void t_cycles(void) {
  //LDA #imm 8-bit: 2 cycles.
  setup(); LOAD(0x8000, 0xa9, 0x00); cpu_step(&cpu);
  CHECK(cycles == 2);
  //Native, 16-bit X: LDA abs,X always 5 cycles in M=8.
  setup(); LOAD(0x8000, NATIVE, REP(0x10), 0xbd, 0x00, 0x20);
  cpu_step(&cpu); cpu_step(&cpu); cpu_step(&cpu); cycles = 0; cpu_step(&cpu);
  CHECK(cycles == 5);
  //8-bit X, no page cross: 4 cycles.
  setup(); LOAD(0x8000, 0xbd, 0x00, 0x20); cpu_step(&cpu);
  CHECK(cycles == 4);
  //DL != 0 adds a cycle on dp: LDA dp = 4.
  setup(); LOAD(0x8000, NATIVE, REP(0x20), 0xa9, 0x01, 0x00, 0x5b, SEP(0x20), 0xa5, 0x10);
  for (int i = 0; i < 6; i++) cpu_step(&cpu);
  cycles = 0; cpu_step(&cpu);
  CHECK(cycles == 4);
  //JSL 8, RTL 6.
  setup(); LOAD(0x8000, NATIVE, 0x22, 0x00, 0x90, 0x00); LOAD(0x9000, 0x6b);
  cpu_step(&cpu); cpu_step(&cpu); cycles = 0; cpu_step(&cpu);
  CHECK(cycles == 8);
  cycles = 0; cpu_step(&cpu);
  CHECK(cycles == 6);
  //MVN 7 per byte.
  setup(); LOAD(0x8000, 0x54, 0x00, 0x00); cpu.a = 5; cpu_step(&cpu);
  CHECK(cycles == 7);
  //16-bit RMW dp: ASL dp = 7 (M=0).
  setup(); LOAD(0x8000, NATIVE, REP(0x20), 0x06, 0x10);
  cpu_step(&cpu); cpu_step(&cpu); cpu_step(&cpu); cycles = 0; cpu_step(&cpu);
  CHECK(cycles == 7);
}

