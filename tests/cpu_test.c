#include <stdio.h>
#include <string.h>
#include "../src/snes/cpu.h"

static uint8_t mem[1 << 24];
static unsigned long cycles;
static Cpu cpu;
static int npass, nfail;

static uint8_t mrd(void *ctx, uint32_t a) { (void)ctx; cycles++; return mem[a & 0xffffff]; }
static void mwr(void *ctx, uint32_t a, uint8_t v) { (void)ctx; cycles++; mem[a & 0xffffff] = v; }
static void midle(void *ctx) { (void)ctx; cycles++; }

#define CHECK(cond) do { \
  if (cond) npass++; \
  else { nfail++; printf("FAIL %s:%d: %s\n", __FILE__, __LINE__, #cond); } \
} while (0)

#define LOAD(addr, ...) do { \
  static const uint8_t b_[] = { __VA_ARGS__ }; \
  memcpy(mem + (addr), b_, sizeof b_); \
} while (0)

static void setup(void) {
  memset(mem, 0, sizeof mem);
  memset(&cpu, 0, sizeof cpu);
  cpu.read = mrd; cpu.write = mwr; cpu.idle = midle;
  mem[0xfffc] = 0x00; mem[0xfffd] = 0x80;
  cpu_reset(&cpu);
  cycles = 0;
}

static void run(void) {
  for (int i = 0; i < 100000 && !cpu.stopped; i++) cpu_step(&cpu);
}

//Runs code at $00:8000 until STP.
#define PROG(...) do { setup(); LOAD(0x8000, __VA_ARGS__); run(); } while (0)

#define NATIVE 0x18, 0xfb
#define REP(v) 0xc2, v
#define SEP(v) 0xe2, v
#define STP 0xdb

static bool flag(uint8_t f) { return cpu.p & f; }

static void t_reset(void) {
  setup();
  CHECK(cpu.e && cpu.p == 0x34 && cpu.s == 0x01ff && cpu.pc == 0x8000);
  CHECK(cpu.d == 0 && cpu.db == 0 && cpu.pb == 0);
}

static void t_adc_sbc_binary(void) {
  PROG(0x18, 0xa9, 0x50, 0x69, 0x50, STP);
  CHECK((cpu.a & 0xff) == 0xa0 && flag(CPU_V) && flag(CPU_N) && !flag(CPU_C) && !flag(CPU_Z));
  PROG(0x18, 0xa9, 0xff, 0x69, 0x01, STP);
  CHECK((cpu.a & 0xff) == 0x00 && flag(CPU_C) && flag(CPU_Z) && !flag(CPU_V));
  PROG(0x38, 0xa9, 0x50, 0xe9, 0xb0, STP);
  CHECK((cpu.a & 0xff) == 0xa0 && flag(CPU_V) && !flag(CPU_C) && flag(CPU_N));
  PROG(0x38, 0xa9, 0x05, 0xe9, 0x03, STP);
  CHECK((cpu.a & 0xff) == 0x02 && flag(CPU_C) && !flag(CPU_V));
  //8-bit op leaves B intact.
  PROG(NATIVE, REP(0x20), 0xa9, 0x34, 0x12, SEP(0x20), 0x18, 0x69, 0x01, STP);
  CHECK(cpu.a == 0x1235);
  PROG(NATIVE, REP(0x20), 0x18, 0xa9, 0xff, 0x7f, 0x69, 0x01, 0x00, STP);
  CHECK(cpu.a == 0x8000 && flag(CPU_V) && flag(CPU_N) && !flag(CPU_C));
  PROG(NATIVE, REP(0x20), 0x18, 0xa9, 0xff, 0xff, 0x69, 0x01, 0x00, STP);
  CHECK(cpu.a == 0x0000 && flag(CPU_C) && flag(CPU_Z) && !flag(CPU_V));
  PROG(NATIVE, REP(0x20), 0x38, 0xa9, 0x00, 0x00, 0xe9, 0x01, 0x00, STP);
  CHECK(cpu.a == 0xffff && !flag(CPU_C) && flag(CPU_N) && !flag(CPU_V));
  PROG(NATIVE, REP(0x20), 0x38, 0xa9, 0x00, 0x80, 0xe9, 0x01, 0x00, STP);
  CHECK(cpu.a == 0x7fff && flag(CPU_C) && flag(CPU_V));
}

